package com.heroicpaths.rpg.tree;

public enum NodeType {
    /** Старт класса: свой изучен бесплатно, через чужой можно пройти как через обычный узел. */
    START,
    /** Малый узел: небольшая прибавка. */
    SMALL,
    /** Значимый узел: заметная прибавка с собственным именем. */
    NOTABLE,
    /** Ключевой камень: меняет правила игры. */
    KEYSTONE
}
